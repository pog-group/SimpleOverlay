const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getStore: () => ipcRenderer.invoke('get-store'),
  getState: () => ipcRenderer.invoke('get-state'),
  getDisplays: () => ipcRenderer.invoke('get-displays'),
  listWindows: () => ipcRenderer.invoke('list-windows'),
  showOverlay: () => ipcRenderer.send('show-overlay'),
  hideOverlay: () => ipcRenderer.send('hide-overlay'),
  setAudioMuted: (muted) => ipcRenderer.send('set-audio-muted', muted),
  reloadOverlay: () => ipcRenderer.send('reload-overlay'),
  clearCacheReload: () => ipcRenderer.send('clear-cache-reload'),
  setUrl: (url, show = false) => ipcRenderer.invoke('set-url', { url, show }),
  setTarget: (target) => ipcRenderer.send('set-target', target),
  setPageWidth: (width) => ipcRenderer.send('set-page-width', width),
  setHideUnfocused: (value) => ipcRenderer.send('set-hide-unfocused', value),
  saveUrl: (url) => ipcRenderer.invoke('save-url', url),
  moveSaved: (url, beforeUrl) => ipcRenderer.send('move-saved', url, beforeUrl),
  removeSaved: (url) => ipcRenderer.send('remove-saved', url),
  removeHistory: (url) => ipcRenderer.send('remove-history', url),
  clearHistory: () => ipcRenderer.send('clear-history'),
  interactOverlay: (mode) => ipcRenderer.send('interact-overlay', mode),
  stopInteractOverlay: () => ipcRenderer.send('stop-interact-overlay'),
  onStoreUpdated: (cb) => ipcRenderer.on('store-updated', (_, data) => cb(data)),
  onOverlayState: (cb) => ipcRenderer.on('overlay-state', (_, visible) => cb(visible)),
  onInteractState: (cb) => ipcRenderer.on('interact-state', (_, mode) => cb(mode)),
  onCanShow: (cb) => ipcRenderer.on('can-show', (_, value) => cb(value)),
  installUpdate: () => ipcRenderer.send('install-update'),
  onUpdateState: (cb) => ipcRenderer.on('update-state', (_, update) => cb(update)),
  onTarget: (cb) => ipcRenderer.on('target', (_, target) => cb(target)),
  onStatus: (cb) => ipcRenderer.on('status', (_, status) => cb(status)),
});
